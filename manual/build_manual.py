def font_style(style,size,bold=False):
    style.font.name='Tahoma';style.font.size=Pt(size);style.font.bold=bold;style.font.color.rgb=RGBColor(0,0,0)
    el=style.element.get_or_add_rPr();fonts=el.find(qn('w:rFonts'))
    if fonts is None:fonts=OxmlElement('w:rFonts');el.insert(0,fonts)
    for k in ['ascii','hAnsi','eastAsia','cs']:fonts.set(qn('w:'+k),'Tahoma')

def paragraph(doc,text,style=None,bold=None):
    p=doc.add_paragraph(style=style);r=p.add_run(text)
    if bold is not None:r.bold=bold
    p.paragraph_format.space_after=Pt(7);return p

def image(doc,name,caption):
    pth=SCREENS/(name+'.png')
    if not pth.exists():return
    with Image.open(pth) as im:w,h=im.size
    width=min(6.45,3.30*w/h)
    p=doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    run=p.add_run();shape=run.add_picture(str(pth),width=Inches(width))
    shape._inline.docPr.set('descr',caption)
    p.paragraph_format.space_after=Pt(3)
    p=paragraph(doc,caption,'Caption');p.alignment=WD_ALIGN_PARAGRAPH.CENTER

