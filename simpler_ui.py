def settings_destination(action, fallback):
    return {
        '/settings': '/settings?tab=shop',
        '/deposit-settings': '/settings?tab=shop#deposit-settings',
        '/deposit-qr': '/settings?tab=shop#deposit-settings',
        '/user': '/settings?tab=staff',
        '/staff-station': '/settings?tab=staff',
        '/password': '/settings?tab=security',
        '/deposit-action': '/reservations?view=deposits',
    }.get(action, fallback)


def settings_page(h, db, body, staff):
    # These five sections are generated by the settings view, never user HTML.
    sections = re.findall(r'<section\b.*?</section>', body, re.S)
    if len(sections) != 5:
        raise ValueError('ไม่สามารถจัดหน้าตั้งค่าได้ กรุณาติดต่อผู้ดูแล')
    tabs = [('shop', 'ร้านและมัดจำ'), ('staff', 'พนักงาน'),
            ('security', 'ความปลอดภัย'), ('backup', 'สำรองข้อมูล'),
            ('history', 'ประวัติการทำรายการ')]
    selected = h.query.get('tab', ['shop'])[0]
    if selected not in dict(tabs):
        selected = 'shop'
    nav = '<nav class="workspace-tabs" aria-label="หมวดการตั้งค่า">'
    for key, label in tabs:
        active = ' aria-current="page"' if selected == key else ''
        nav += f'<a class="button {"" if selected == key else "secondary"}" href="/settings?tab={key}"{active}>{label}</a>'
    nav += '</nav>'
    pages = {
        'shop': sections[0] + '<div id=deposit-settings>' + deposits.configuration(h, db) + '</div>',
        'staff': sections[1] + staff,
        'security': sections[2] + '<section class=panel><h2>กู้คืนบัญชี</h2><p>จัดการแนวทางกู้คืนบัญชีแยกจากการสร้างพนักงาน</p><a class="button secondary" href=/account-security>จัดการการกู้คืนบัญชี →</a></section>',
        'backup': sections[3],
        'history': sections[4],
    }
    return '<style>.workspace-tabs{display:flex;gap:10px;flex-wrap:wrap;margin:0 0 22px}.workspace-tabs a{white-space:normal}.workspace-tabs a[aria-current=page]{color:#15251d!important;box-shadow:0 0 0 2px #efcc8c;outline-offset:3px}</style>' + nav + pages[selected]


def reservations_page(h, db, body):
    form, records = body.split('</section>', 1)
    selected = h.query.get('view', ['deposits' if 'deposits' in h.query else 'bookings'])[0]
    tabs = [('bookings', 'รายการจอง / รับลูกค้า'), ('new', 'สร้างการจองใหม่')]
    if h.s['role'] == 'manager':
        tabs.insert(1, ('deposits', 'ตรวจมัดจำ / คืนเงิน'))
    if selected not in dict(tabs):
        selected = 'bookings'
    nav = '<nav class="reservation-tabs" aria-label="งานการจอง" style="display:flex;gap:10px;flex-wrap:wrap;margin-bottom:22px">'
    for key, label in tabs:
        current = ' aria-current="page"' if selected == key else ''
        nav += f'<a class="button {"" if selected == key else "secondary"}" href="/reservations?view={key}"{current}>{label}</a>'
    nav += '</nav>'
    if selected == 'new':
        content = form + '</section>'
    elif selected == 'deposits':
        content = deposits.admin(h, db)
    else:
        tip = 'ตรวจมัดจำในแท็บด้านบน' if h.s['role'] == 'manager' else 'หากมัดจำยังรอตรวจ ให้ผู้จัดการยืนยันก่อนรับลูกค้า'
        content = '<p>ค้นหารายการ แล้วกด รับลูกค้า / เปิดโต๊ะ เมื่อมาถึง · ' + tip + '</p>' + records
    return nav + content


def latest_order(h, db):
    visit = h.active_visit(db)
    if not visit:
        return ''
    r = db.execute('SELECT id,status,created FROM customer_requests WHERE session_token=? AND order_id=? ORDER BY id DESC LIMIT 1', (h.c['token'], visit['id'])).fetchone()
    if not r:
        return ''
    labels = {'received': 'ร้านรับออเดอร์แล้ว', 'preparing': 'กำลังจัดเตรียม',
              'ready': 'พร้อมเสิร์ฟ', 'served': 'เสิร์ฟแล้ว', 'cancelled': 'ยกเลิกแล้ว'}
    return f'<section class="panel latest-order" aria-label="ออเดอร์ล่าสุด"><strong>ออเดอร์ล่าสุด #{r["id"]:04} · {labels.get(r["status"], "รออัปเดต")}</strong><p>สั่งเมื่อ {h.api.esc(h.api.ux.date(r["created"]))} · อัปเดตอัตโนมัติ</p><a class="button secondary" href="/my-orders#request-{r["id"]}">ดูรายละเอียด / เรียกพนักงาน →</a></section>'


